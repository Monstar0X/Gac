#!/usr/bin/env node
/**
 * Generate invite codes for the closed beta.
 *
 *   node tools/make-invites.mjs            # 10 codes (BETA.maxTesters)
 *   node tools/make-invites.mjs 6          # fewer
 *
 * Writes:
 *   src/beta/invites.generated.ts   hashes only, committed and shipped
 *   INVITE-CODES.txt                the codes themselves, for YOU to hand out
 *                                   (git-ignored; never deploy it)
 *
 * Re-running replaces every code, which revokes all earlier invites once the
 * new build is deployed.
 */
import { createHash, randomInt } from 'node:crypto';
import { writeFileSync } from 'node:fs';

const SALT = 'wg3d-beta:';
const n = Math.min(10, Math.max(1, Number(process.argv[2] ?? 10)));
const ALPHABET = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789'; // no 0/O/1/I confusion
const part = () => Array.from({ length: 4 }, () => ALPHABET[randomInt(ALPHABET.length)]).join('');

const codes = Array.from({ length: n }, () => `LUCK-${part()}-${part()}`);
const hashes = codes.map((c) => createHash('sha256').update(SALT + c.replace(/[^A-Z0-9]/g, '')).digest('hex'));

writeFileSync(
  new URL('../src/beta/invites.generated.ts', import.meta.url),
  `/**\n * GENERATED by \`node tools/make-invites.mjs\`. Do not edit by hand.\n *\n * Holds SHA-256 hashes of the invite codes, never the codes themselves, so\n * the bundle does not reveal them. An empty list disables the gate (dev mode).\n */\nexport const INVITE_HASHES: string[] = [\n${hashes.map((h) => `  '${h}',`).join('\n')}\n];\n`,
);
writeFileSync(
  new URL('../INVITE-CODES.txt', import.meta.url),
  `WAIFU GACHA closed beta invite codes (${new Date().toISOString().slice(0, 10)})\nKeep private. One code per tester.\n\n${codes.map((c, i) => `T${String(i + 1).padStart(2, '0')}  ${c}   tester: ____________`).join('\n')}\n`,
);
console.log(`Wrote ${n} invites. Hand out INVITE-CODES.txt entries; do NOT deploy that file.`);
